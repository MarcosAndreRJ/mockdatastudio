using System.Globalization;
using System.Text;
using MockDataStudio.Core.Common;
using MockDataStudio.Core.Naming;
using MockDataStudio.Core.Schema;
using MockDataStudio.Providers.Models;

namespace MockDataStudio.Providers.PostgreSql;

// Dialeto PostgreSQL: quoting, literais, INSERT e sessão (docs/10 §5, docs/11).
// Sem desligamento de FK por sessão: exige papel de superusuário (session_replication_role), por isso retorna null.
public sealed class PostgreSqlDialect : ISqlDialect
{
    public DatabaseEngine Engine => DatabaseEngine.PostgreSql;

    public ISqlLiteralFormatter Literals { get; } = new PostgreSqlLiteralFormatter();

    public string StatementTerminator => ";";

    public string? BeginTransaction => "BEGIN;";

    public string Commit => "COMMIT;";

    // Limite conservador de linhas por INSERT multi-linha (VALUES).
    public int RecommendedRowsPerInsert => 500;

    public string QuoteIdentifier(string identifier) =>
        "\"" + identifier.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";

    public string QualifiedName(ObjectName name) => QuoteIdentifier(name.Namespace) + "." + QuoteIdentifier(name.Name);

    // standard_conforming_strings garante que barras invertidas em literais não sejam escapes.
    public IReadOnlyList<string> SessionPreamble(ScriptOptions options) => ["SET standard_conforming_strings = on;"];

    public string? DisableFkChecks() => null;

    public string? EnableFkChecks() => null;

    // Identidade GENERATED ALWAYS exige OVERRIDING SYSTEM VALUE para aceitar valor explícito.
    // GENERATED BY DEFAULT e serial aceitam valor explícito sem cláusula.
    public string? IdentityOverrideClause(ColumnModel identityColumn) =>
        identityColumn.Identity?.Kind == IdentityKind.IdentityAlways ? "OVERRIDING SYSTEM VALUE" : null;

    // Ressincroniza a sequence para que o próximo nextval() devolva nextValue (is_called = false).
    public IReadOnlyList<string> ResyncSequenceStatements(ObjectName table, ColumnModel column, string? sequenceName, long nextValue)
    {
        if (string.IsNullOrEmpty(sequenceName))
        {
            return [];
        }

        var regclass = PostgreSqlLiteralFormatter.Text(sequenceName);
        return [$"SELECT setval({regclass}, {nextValue.ToString(CultureInfo.InvariantCulture)}, false);"];
    }

    public string BuildInsert(ObjectName table, IReadOnlyList<string> columns, IReadOnlyList<IReadOnlyList<string>> literalRows, string? overrideClause)
    {
        var sb = new StringBuilder();
        sb.Append("INSERT INTO ").Append(QualifiedName(table)).Append(" (")
          .Append(string.Join(", ", columns.Select(QuoteIdentifier))).Append(')');
        if (!string.IsNullOrEmpty(overrideClause))
        {
            sb.Append(' ').Append(overrideClause);
        }

        sb.Append(" VALUES\n");
        for (var r = 0; r < literalRows.Count; r++)
        {
            sb.Append('(').Append(string.Join(", ", literalRows[r])).Append(')');
            sb.Append(r == literalRows.Count - 1 ? ";" : ",\n");
        }

        return sb.ToString();
    }
}

// Literais PostgreSQL. Valores untyped entre aspas são coagidos pelo servidor ao tipo da coluna.
public sealed class PostgreSqlLiteralFormatter : ISqlLiteralFormatter
{
    public string Null => "NULL";

    public string Format(object? value, DataTypeInfo type)
    {
        return value switch
        {
            null => Null,
            bool b => b ? "TRUE" : "FALSE",
            sbyte or byte or short or ushort or int or uint or long or ulong =>
                Convert.ToString(value, CultureInfo.InvariantCulture)!,
            decimal m => m.ToString(CultureInfo.InvariantCulture),
            float f => Floating(f),
            double d => Floating(d),
            DateTime dt => Text(dt.ToString("yyyy-MM-dd HH:mm:ss.ffffff", CultureInfo.InvariantCulture)),
            DateTimeOffset dto => Text(dto.ToString("yyyy-MM-dd HH:mm:ss.ffffffzzz", CultureInfo.InvariantCulture)),
            DateOnly d => Text(d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)),
            TimeOnly t => Text(t.ToString("HH:mm:ss.ffffff", CultureInfo.InvariantCulture)),
            Guid g => Text(g.ToString("D", CultureInfo.InvariantCulture)),
            byte[] bytes => Text("\\x" + Convert.ToHexString(bytes).ToLowerInvariant()),
            string s => Text(s),
            _ => Text(Convert.ToString(value, CultureInfo.InvariantCulture) ?? string.Empty),
        };
    }

    // PostgreSQL não armazena NUL em text/varchar: recusar é melhor do que gerar um script que falha no servidor.
    public static string Text(string text)
    {
        if (text.Contains('\0', StringComparison.Ordinal))
        {
            throw new ArgumentOutOfRangeException(nameof(text), "PostgreSQL não aceita caractere NUL em texto.");
        }

        return "'" + text.Replace("'", "''", StringComparison.Ordinal) + "'";
    }

    private static string Floating(double d)
    {
        if (double.IsNaN(d))
        {
            return "'NaN'::double precision";
        }

        if (double.IsPositiveInfinity(d))
        {
            return "'Infinity'::double precision";
        }

        if (double.IsNegativeInfinity(d))
        {
            return "'-Infinity'::double precision";
        }

        return d.ToString("R", CultureInfo.InvariantCulture);
    }
}
